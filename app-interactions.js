// Controls and interaction handlers
function finish(){pointerDrawing=false;
let completedPortRoute=false;
if(draft.length>=2){let featureOn=$('#threadFeaturesToggle')?.getAttribute('aria-pressed')==='true';
if(mode==='signal'&&featureOn&&(!signalPortArmed||!selectedSignalPort||allSignalRouteRecords().some(x=>Number(x.route.portNumber)===selectedSignalPort))){toast('Choose an available port in the bottom bar before drawing a signal route');
draft=[];
signalPortArmed=false;
setMode('select');
return}if(mode==='power'&&featureOn&&(bottomPortMode!=='power'||!powerPortArmed||selectedPowerPort<1||selectedPowerPort>36)){toast('Choose an available Power port in the bottom bar before drawing a power route');
draft=[];
powerPortArmed=false;
setMode('select');
return}let route={id:Date.now()+Math.random(),type:mode,points:[...draft]};
if(mode==='signal'&&featureOn){route.portNumber=selectedSignalPort;
completedPortRoute=true}if(mode==='power'&&featureOn&&bottomPortMode==='power'){route.powerPortNumber=selectedPowerPort;
completedPortRoute=true}routes.push(route)}else if(draft.length)toast('Add at least one more point');
draft=[];
if(completedPortRoute){signalPortArmed=false;
powerPortArmed=false;
selectedRoute=null;
setMode('select');
return}render()}
function setMode(m){if(draft.length)finish();
if(m!=='signal')signalPortArmed=false;
if(m!=='power')powerPortArmed=false;
mode=m;
document.querySelectorAll('.route-btn').forEach(b=>b.classList.toggle('active',b.dataset.mode===m));
$('#selectTool').classList.toggle('active',m==='select');
$('#powerTool').classList.toggle('active',m==='power');
$('#signalTool').classList.toggle('active',m==='signal');
$('#hint').textContent=m==='select'?'Choose a cable, then click or drag across cabinet centers to trace the route. Enter finishes; Backspace undoes.':`Click or drag across panel centers to add ${m} route points. Enter finishes; Backspace undoes.`;
$('#emptyHint').textContent=m==='select'?'Select a cable type, then click or drag across cabinet centers to start a route':'Click or drag across cabinet centers · Enter finishes · Backspace undoes';
$('#wallSvg').style.cursor=m==='select'?'default':'crosshair';
render()}
function zoom(n){scale=Math.max(.01,Math.min(1.5,n));
$('#zoomLabel').textContent=Math.round(scale*100)+'%';
render()}
function toast(s){let t=$('#toast');
t.textContent=s;
t.classList.add('show');
clearTimeout(toastTimer);
toastTimer=setTimeout(()=>t.classList.remove('show'),1800)}document.querySelectorAll('.route-btn').forEach(b=>b.onclick=()=>setMode(b.dataset.mode));
$('#wallMountToggle').onclick=()=>{wallMount=wallMount==='floor'?'hanging':'floor';
captureActivePage();
syncWallMountButton();
render();
if(systemView)fitSystemCanvas()};
function syncWallMountButton(){let button=$('#wallMountToggle'),floor=wallMount==='floor';
button.textContent=floor?'Floor':'Hanging';
button.setAttribute('aria-checked',String(floor));
button.classList.toggle('active',floor)}syncWallMountButton();
$('#selectTool').onclick=()=>setMode('select');
$('#powerTool').onclick=()=>setMode('power');
$('#signalTool').onclick=()=>setMode('signal');
$('#togglePower').onclick=()=>{visibleFlows.power=!visibleFlows.power;
let b=$('#togglePower');
b.textContent=visibleFlows.power?'Hide Power':'Show Power';
b.setAttribute('aria-pressed',String(visibleFlows.power));
b.classList.toggle('visibility-off',!visibleFlows.power);
render()};
$('#toggleSignal').onclick=()=>{visibleFlows.signal=!visibleFlows.signal;
let b=$('#toggleSignal');
b.textContent=visibleFlows.signal?'Hide Signal':'Show Signal';
b.setAttribute('aria-pressed',String(visibleFlows.signal));
b.classList.toggle('visibility-off',!visibleFlows.signal);
render()};
for(const id of ['wallWidth','wallHeight'])document.getElementById(id).onchange=()=>{let entered=Math.max(.5,Math.min(50,Math.round((+document.getElementById(id).value||.5)*2)/2)),raw=Math.round(entered*1000);
if(id==='wallWidth')wallWidth=Math.max(cw,Math.min(50000,Math.round(raw/cw)*cw));
else wallHeight=raw;
document.getElementById('wallWidth').value=(wallWidth/1000).toFixed(1);
document.getElementById('wallHeight').value=(wallHeight/1000).toFixed(1);
render();
$('#fitBtn').click()};
$('#finishBtn').onclick=()=>finish();
$('#undoBtn').onclick=()=>{if(draft.length){draft.pop();
render()}else if(routes.length){let removed=routes.pop();
if(removed.id===selectedRoute)selectedRoute=null;
render()}else toast('Nothing to undo')};
$('#resetBtn').onclick=()=>{routes=[];
draft=[];
selectedRoute=null;
setMode('select');
render();
toast('Routes cleared')};
$('#minus').onclick=()=>zoom(scale-.1);
$('#plus').onclick=()=>zoom(scale+.1);
$('#zoomLabel').onclick=()=>zoom(1);
$('#fitBtn').onclick=()=>{let {w,h}=systemView&&systemCanvasSize?systemCanvasSize:dims();
zoom(Math.min(1,(innerWidth-310)/(w+60),(innerHeight-180)/(h+60)))};
$('#labelsBtn').onclick=()=>{labels=!labels;
$('#labelsBtn').textContent=labels?'Hide cabinet labels':'Show cabinet labels';
render()};
$('#typePower').onclick=()=>{let r=routes.find(q=>q.id===selectedRoute);
if(r){if(r.points.some(p=>tileUsedByOtherRoute(p,'power',r.id))){toast('A Power route already uses one or more of these cabinets');
return}r.type='power';
render()}};
$('#typeSignal').onclick=()=>{let r=routes.find(q=>q.id===selectedRoute);
if(r){if(r.points.some(p=>tileUsedByOtherRoute(p,'signal',r.id))){toast('A Signal route already uses one or more of these cabinets');
return}r.type='signal';
render()}};
$('#reverseRoute').onclick=()=>{let r=routes.find(q=>q.id===selectedRoute);
if(r){r.points.reverse();
render()}};
$('#deleteRoute').onclick=()=>{routes=routes.filter(q=>q.id!==selectedRoute);
selectedRoute=null;
render()};
document.addEventListener('pointermove',moveRoutePoint);
$('#boardwrap').addEventListener('pointerdown',beginPan);
$('#boardwrap').addEventListener('wheel',handleCanvasWheel,{passive:false});
document.addEventListener('pointerup',()=>{draggingPoint=null;pointerDrawing=false;panning=null;document.body.style.cursor=panCursor});
document.addEventListener('pointercancel',()=>{draggingPoint=null;pointerDrawing=false;panning=null;document.body.style.cursor=panCursor});
